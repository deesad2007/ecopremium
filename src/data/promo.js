// ─────────────────────────────────────────────────────────────
// Промокоды со старого сайта. Проценты проверяются ТОЛЬКО на сервере:
// из браузера приходит лишь introduced код, скидку считает /api/pay.
// Иначе процент можно было бы подставить любой прямо в консоли.
//
// Коды сравниваются без учёта регистра и лишних пробелов.
// ─────────────────────────────────────────────────────────────

export const promoCodes = {
  // 5%
  maslo: 5,
  eko: 5,
  stock: 5,
  luxe: 5,
  deluxe: 5,
  bio: 5,
  eco: 5,
  elit: 5,
  discount: 5,

  // 10%
  ekopremi: 10,

  // 20%
  organik: 20,

  // ВНИМАНИЕ: код «premi» в присланном списке встречается дважды, среди
  // пятипроцентных и как пятнадцатипроцентный. Пока владелец не скажет,
  // какой верный, код намеренно не включён: покупатель увидит «промокод
  // не найден», а это честнее, чем угаданная скидка на реальных деньгах.
  // premi: 15,
};

/** Процент скидки по коду. Ноль означает, что кода нет. */
export function promoPercent(code) {
  const key = String(code || '').trim().toLowerCase();
  return promoCodes[key] || 0;
}
